#!/usr/bin/env python3
"""
=============================================================================
Script: 3-generate_fasta.py
Author: Ivan Espejo
Function: Extracts the 140bp V4 region from the master FASTA, deduplicates 
          identical sequences, and updates the global OTU table.

Usage: 
    python 3-generate_fasta.py -f <input_fasta> -t <input_table> [options]

Info: 
- Takes the master FASTA and TSV generated by Step 2.
- Relies on 'cutadapt' to isolate the V4 region.
- Deduplicates taxa that collapse into identical 140bp sequences.
- Merges abundances of deduplicated taxa in raw compositional space.
- Drops taxa from the TSV that fail cutadapt or are missing from the FASTA.
- Removes the 'Taxon' column from the final output TSV.
=============================================================================
"""

import argparse
import os
import subprocess

def process_and_merge(fasta_in, tsv_in, fasta_out, tsv_out, primer):
    if not os.path.exists(fasta_in):
        print(f"[!] Error: Input FASTA '{fasta_in}' not found.")
        return
    if not os.path.exists(tsv_in):
        print(f"[!] Error: Input TSV '{tsv_in}' not found.")
        return

    os.makedirs("output/preprocessing/tmp", exist_ok=True)
    cropped_fasta = "output/preprocessing/tmp/temp_cropped.fasta"

    # 1. Run cutadapt
    print(f"1. Running cutadapt to extract 140bp V4 region using primer '{primer}'...")
    subprocess.run([
        "cutadapt", "-g", primer, "-l", "140", "--discard-untrimmed", 
        "-o", cropped_fasta, fasta_in
    ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True)

    # 2. Deduplicate identical 140bp sequences
    print("2. Deduplicating identical sequences...")
    seq2fullheader = {}  # Maps sequence -> Full header (ID + Taxonomy)
    id_map = {}          # Maps original ID -> Kept ID

    if os.path.exists(cropped_fasta):
        with open(cropped_fasta, 'r') as f:
            h, s = "", ""
            for line in f:
                line = line.strip()
                if line.startswith('>'):
                    if h:
                        orig_id = h.split()[0]  # Extract just the ID part
                        if s in seq2fullheader:
                            kept_id = seq2fullheader[s].split()[0]
                            id_map[orig_id] = kept_id
                        else:
                            seq2fullheader[s] = h
                            id_map[orig_id] = orig_id
                    h, s = line[1:], ""
                else:
                    s += line
            if h:  # Handle the last sequence
                orig_id = h.split()[0]
                if s in seq2fullheader:
                    kept_id = seq2fullheader[s].split()[0]
                    id_map[orig_id] = kept_id
                else:
                    seq2fullheader[s] = h
                    id_map[orig_id] = orig_id

    # Write the final deduplicated FASTA
    os.makedirs(os.path.dirname(fasta_out) or '.', exist_ok=True)
    with open(fasta_out, 'w') as fout:
        for seq, full_h in seq2fullheader.items():
            fout.write(f">{full_h}\n{seq}\n")

    # 3. Update the OTU Table and Merge Abundances
    print("3. Updating OTU table, merging abundances, and dropping Taxon column...")
    merged_data = {}
    original_otu_count = 0
    missing_tsv_ids = set()
    
    with open(tsv_in, 'r') as f:
        header = next(f).rstrip('\n').split('\t')
        
        # Identify the Taxon column to drop it
        tax_idx = -1
        for i, col in enumerate(header):
            if col.lower() in ['taxon', 'taxonomy']: tax_idx = i
        
        # Extract indices and names for all sample columns (Skipping ID and Taxon)
        sample_indices = [i for i in range(len(header)) if i != 0 and i != tax_idx]
        sample_cols = [header[i] for i in sample_indices]
        
        for line in f:
            p = line.rstrip('\n').split('\t')
            if len(p) < 2: continue
            original_otu_count += 1
            oid = p[0]
            
            # If the ID didn't survive cutadapt OR wasn't in the FASTA, drop it
            if oid not in id_map:
                missing_tsv_ids.add(oid)
                continue
                
            kept_id = id_map[oid]
            
            # Initialize array for new kept_id if not present
            if kept_id not in merged_data:
                merged_data[kept_id] = [0.0] * len(sample_cols)
                
            # Merge abundance values
            for j, idx in enumerate(sample_indices):
                if idx < len(p):
                    try: merged_data[kept_id][j] += float(p[idx])
                    except ValueError: pass

    # Write the final TSV (Without the Taxon column)
    os.makedirs(os.path.dirname(tsv_out) or '.', exist_ok=True)
    with open(tsv_out, 'w') as fout:
        fout.write("UnifiedID\t" + "\t".join(sample_cols) + "\n")
        for gid, vals in merged_data.items():
            row = [gid] + [str(v) for v in vals]
            fout.write("\t".join(row) + "\n")

    # 4. Cleanup and Logging
    if os.path.exists(cropped_fasta):
        os.remove(cropped_fasta)
    
    dups = len(id_map) - len(seq2fullheader)
    with open("output/preprocessing/tmp/pipeline_drops.log", "a") as log:
        log.write(f"\n---Script {os.path.basename(__file__)} -------\n\n=== TAXA MERGED (DEDUPLICATION) ===\n")
        merged_logs = [f"Dropped: {o} -> Kept: {g}" for o, g in id_map.items() if o != g]
        log.write("\n".join(merged_logs) + "\n" if merged_logs else "None\n")
        
        log.write(f"\n=== TAXA REMOVED (MISSING PRIMER / TOO SHORT / NOT IN FASTA) ===\n")
        log.write("\n".join(sorted(list(missing_tsv_ids))) + "\n" if missing_tsv_ids else "None\n")

    print(f"\n=== V4 Extraction & Deduplication Summary ===")
    print(f"1. OTUs in input table: {original_otu_count}")
    print(f"2. OTUs in final dedup table: {len(merged_data)}")
    print(f"3. Difference breakdown (Total removed: {original_otu_count - len(merged_data)}):")
    print(f"   - Removed by deduplication (merged): {dups}")
    print(f"   - Removed because missing primer/too short/not in FASTA: {len(missing_tsv_ids)}")
    print(f"4. Outputs saved to:\n   - FASTA: {fasta_out}\n   - TSV: {tsv_out}\n")

def parse_args():
    p = argparse.ArgumentParser(description="Extract 140bp V4 regions, deduplicate, and merge TSV.")
    p.add_argument('-f', '--fasta', default="../data/input/merged_seqs.fasta", 
                   help="Input master FASTA file generated by step 2.")
    p.add_argument('-t', '--table', default="../data/input/raw_global_otu_dedup.tsv", 
                   help="Input merged OTU table generated by step 2.")
    p.add_argument('-of', '--out_fasta', default="output/preprocessing/global_V4.fasta", 
                   help="Output FASTA containing deduplicated 140bp sequences.")
    p.add_argument('-ot', '--out_tsv', default="output/preprocessing/global_V4_otu.tsv", 
                   help="Output TSV containing merged abundances (Taxon col removed).")
    p.add_argument('-p', '--primer', default="GTGYCAGCMGCCGCGGTAA", 
                   help="Forward primer for cutadapt.")
    return p.parse_args()


if __name__ == '__main__':
    args = parse_args()
    process_and_merge(args.fasta, args.table, args.out_fasta, args.out_tsv, args.primer)