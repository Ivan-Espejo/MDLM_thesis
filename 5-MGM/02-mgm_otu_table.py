#!/usr/bin/env python3
"""
=============================================================================
Script: 03-make_otu_table.py
Author: Ivan Espejo

Description:
    This script converts a raw amplicon abundance matrix into a fully formatted,
    Machine-Learning-ready vocabulary matrix for the MGM (Microbial General Model).

    It performs three critical transformations:
    1. Intersection: Merges raw read counts with the SILVA taxonomy mapping 
       file, automatically dropping sequences that failed the strict VSEARCH alignment.
    2. Nomenclature Translation: Translates raw SILVA taxonomic strings into the 
       Greengenes-style padded format (k__; p__; c__...) required by MGM.
    3. Dimensionality Reduction (Collapsing): Groups all ASVs/OTUs that resolve 
       to the exact same taxonomic lineage and sums their counts, resulting in a 
       unified, deduplicated vocabulary matrix.

Inputs:
    -i / --otu_table : The original raw abundance TSV (Rows = Sequences, Cols = Samples).
    -m / --mapping   : The ID-to-Taxonomy mapping TSV generated by VSEARCH/awk.
    
Outputs:
    -o / --output    : A clean, comma-separated CSV ready for `mgm construct`.
=============================================================================
"""
import pandas as pd
import argparse
import sys
import os

def log_and_print(message, log_path=None):
    """Prints a message to the terminal and optionally appends it to a log file."""
    print(message)
    if log_path:
        try:
            with open(log_path, 'a') as f:
                f.write(message + '\n')
        except Exception as e:
            print(f"[WARNING] Could not write to log file: {e}")

def format_silva_to_mgm(raw_tax_string):
    """Converts raw SILVA strings to the MGM padded format."""
    if pd.isna(raw_tax_string):
        return "Unknown"
        
    prefixes = ['k__', 'p__', 'c__', 'o__', 'f__', 'g__', 's__']
    ranks = [r.strip() for r in str(raw_tax_string).split(';') if r.strip()]
    
    garbage_tags = [
        'uncultured', 'uncultured bacterium', 'uncultured organism', 
        'gut metagenome', 'mouse gut metagenome', 'human gut metagenome', 
        'unidentified', 'metagenome'
    ]
    
    formatted_ranks = []
    for i, prefix in enumerate(prefixes):
        if i < len(ranks) and ranks[i].lower() not in garbage_tags:
            clean_name = ranks[i][3:] if ranks[i][1:3] == '__' else ranks[i]
            formatted_ranks.append(f"{prefix}{clean_name}")
        else:
            formatted_ranks.append(prefix)
            
    return "; ".join(formatted_ranks[:7])

def process_otu_table(otu_table_path, mapping_path, output_path, log_path):
    print("Loading datasets...")
    
    try:
        otu_df = pd.read_csv(otu_table_path, sep='\t')
        mapping_df = pd.read_csv(mapping_path, sep='\t')
    except Exception as e:
        print(f"[ERROR] Failed to load files: {e}")
        sys.exit(1)
    
    id_col = otu_df.columns[0] 
    
    # 1. Track Initial State
    initial_seq_count = otu_df.shape[0]
    
    # 2. Merge Abundances (Drops unaligned sequences)
    merged_df = otu_df.merge(mapping_df, left_on=id_col, right_on='Query_ID', how='inner')
    aligned_seq_count = merged_df.shape[0]
    unaligned_dropped = initial_seq_count - aligned_seq_count
    
    # 3. Track Unique SILVA Lineages (Before cleaning)
    unique_raw_taxa = merged_df['SILVA_Taxonomy'].nunique()
    
    # Clean up dataframe
    drop_cols = [id_col, 'Query_ID']
    if 'Taxon' in merged_df.columns:
        drop_cols.append('Taxon')
    clean_df = merged_df.drop(columns=drop_cols)
    
    # 4. Format and Track Unique MGM Lineages (After cleaning)
    clean_df['MGM_Taxonomy'] = clean_df['SILVA_Taxonomy'].apply(format_silva_to_mgm)
    unique_mgm_taxa = clean_df['MGM_Taxonomy'].nunique()
    taxonomic_collapses = aligned_seq_count - unique_mgm_taxa
    
    # Move taxonomy to index and sum duplicate rows
    clean_df.drop(columns=['SILVA_Taxonomy'], inplace=True)
    clean_df.set_index('MGM_Taxonomy', inplace=True)
    final_df = clean_df.groupby(clean_df.index).sum()
    
    # Save the final CSV
    final_df.to_csv(output_path)
    
    # --- GENERATE SUMMARY ---
    summary = (
        f"\n======================================================\n"
        f"=== PYTHON STAGE: TAXONOMY FORMATTING & COLLAPSE ===\n"
        f"======================================================\n"
        f"1. Initial ASVs in raw table:          {initial_seq_count}\n"
        f"2. ASVs with successful SILVA mapping: {aligned_seq_count} (Dropped: {unaligned_dropped})\n"
        f"------------------------------------------------------\n"
        f"3. Unique SILVA taxonomic strings:     {unique_raw_taxa}\n"
        f"4. Unique MGM taxonomic strings:       {unique_mgm_taxa}\n"
        f"------------------------------------------------------\n"
        f"BIOLOGICAL REDUCTION:\n"
        f" - {taxonomic_collapses} ASVs were collapsed because they share identical\n"
        f"   taxonomy (e.g. multiple strains of the same species,\n"
        f"   or grouped 'uncultured' tags pushed to Family-level).\n"
        f"\nFINAL MATRIX: {final_df.shape[0]} unique taxa x {final_df.shape[1]} samples.\n"
        f"Saved to: {output_path}\n"
        f"======================================================"
    )
    
    # Print to terminal and append to log
    log_and_print(summary, log_path)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Convert raw OTU table to collapsed MGM format.")
    
    parser.add_argument("-i", "--otu_table", required=False, help="Path to raw OTU table (TSV).", default="../data/input/raw_global_otu_dedup.tsv")
    parser.add_argument("-m", "--mapping", required=False, help="Path to VSEARCH mapping file.",default="output/preprocessing/tmp/query_to_taxonomy.tsv")
    parser.add_argument("-o", "--output", required=False, help="Path to save MGM-ready CSV.", default="output/preprocessing/mgm_ready_otu_table.csv")
    parser.add_argument("-l", "--log", required=False, help="Path to pipeline log file to append summary.", default = "output/preprocessing/tmp/pipeline_drops.log")
    
    args = parser.parse_args()
    
    process_otu_table(args.otu_table, args.mapping, args.output, args.log)