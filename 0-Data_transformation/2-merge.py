#!/usr/bin/env python3
"""
=============================================================================
Script: 2-merge.py
Author: Ivan Espejo
Function: Merges multiple OTU tables into a single unified global table, 
          generates a corresponding FASTA file with full 16S sequences, 
          and cross-references metadata with interactive filtering prompts.

Usage: 
    python 2-merge.py -i <input_dir> --outdir <output_dir> [--meta <metadata>]

Info: 
- Scans for all *_unified_tax.tsv files generated by Step 1.
- Resolves sample collisions (renames if biological content differs).
- Interactively drops samples missing from metadata upon user confirmation.
- Extracts full-length sequences and direct taxonomies from reference databases.
- Processes metadata tables (.tsv or .db) to output a strict binary label CSV.
- Provides a final summary report of dropped/retained data in both directions.
=============================================================================
"""
import argparse
import os
import glob
import zipfile
import io
import sys
import pandas as pd
import sqlite3
import re
import time

def main():
    args = parse_args()
    
    # 1. Locate all unified TSV files in the target input directory
    target_files = glob.glob(os.path.join(args.input_dir, "*_unified_tax.tsv"))
    if not target_files:
        print(f"[!] Error: No *_unified_tax.tsv files found in {args.input_dir}. Exiting.")
        sys.exit(1)

    data, sample_registry = {}, {}
    total_taxa_raw, total_samples_raw = 0, 0
    
    print("1. Processing and Merging TSV files...")
    # 2. Iteratively parse each project's TSV and accumulate abundances
    for t_in in target_files:
        proj_clean = os.path.basename(t_in).replace("_unified_tax.tsv", "")
        with open(t_in, 'r') as f:
            header = next(f).rstrip('\n').split('\t')
            tax_idx, sample_indices, f_samples = -1, [], []
            
            for i, col in enumerate(header):
                if i == 0: continue # Skip the FeatureID column (index 0)
                if col.lower() in ['taxon', 'taxonomy']: tax_idx = i
                else:
                    sample_indices.append(i)
                    f_samples.append(col)
                    sample_registry.setdefault(col, []).append(proj_clean)
                    
            total_samples_raw += len(f_samples)
            print(f"   -> {proj_clean}: {len(f_samples)} samples")
            
            for line in f:
                p = line.rstrip('\n').split('\t')
                if len(p) < 2: continue
                oid = p[0]
                total_taxa_raw += 1
                tax = p[tax_idx] if tax_idx != -1 and tax_idx < len(p) else "Unassigned"
                
                if oid not in data: data[oid] = {'tax': tax, 'vals': {}}
                elif tax != "Unassigned" and data[oid]['tax'] == "Unassigned": data[oid]['tax'] = tax
                
                for s_name, idx in zip(f_samples, sample_indices):
                    if idx < len(p):
                        try:
                            v_dict = data[oid]['vals'].setdefault(s_name, {})
                            v_dict[proj_clean] = v_dict.get(proj_clean, 0.0) + float(p[idx])
                        except ValueError: pass 

    print(f"\nIn total: {total_samples_raw} samples processed.\n")
    print("2. Checking for Sample Collisions...")
    
    # 3. Resolve sample naming collisions across different projects
    final_samples, renamed_samples = [], []
    for s_name, projs in sample_registry.items():
        if len(projs) == 1:
            final_samples.append((s_name, s_name, projs[0]))
        else:
            identical = all(all(data[oid]['vals'].get(s_name, {}).get(p, 0.0) == data[oid]['vals'].get(s_name, {}).get(projs[0], 0.0) for p in projs[1:]) for oid in data)
            status = "IDENTICAL (Merged)" if identical else "DIFFERENT (Renamed and Split)"
            print(f"   [!] '{s_name}' repeated in {len(projs)} projects ({', '.join(projs)}) -> {status}")
            
            if identical: final_samples.append((s_name, s_name, projs[0]))
            else:
                for p in projs: 
                    final_samples.append((f"{s_name}_{p}", s_name, p))
                    renamed_samples.append(f"Original: {s_name} -> Renamed: {s_name}_{p}")

    initial_samples_count = len(final_samples)
    dropped_missing_meta = 0
    dropped_unhandled_diag = 0
    missing_in_otu = set()

    print(f"   -> Total unique taxa after merging: {len(data)}")
    print(f"   -> Total unique samples after merging: {initial_samples_count}")

    # 4. Cross-referencing Metadata and Label Preparation
    meta_dict = {}
    labels_out = []
    if args.meta and os.path.exists(args.meta):
        print("\n3. Cross-referencing Metadata and Validating Samples...")
        if args.meta.endswith('.db') or args.meta.endswith('.sqlite'):
            conn = sqlite3.connect(args.meta)
            tables = pd.read_sql_query("SELECT name FROM sqlite_master WHERE type='table';", conn)
            if tables.empty: sys.exit(f"[!] Error: No tables found in database '{args.meta}'.")
            meta_df = pd.read_sql_query(f"SELECT * FROM {tables['name'][0]}", conn)
            conn.close()
        else:
            meta_df = pd.read_csv(args.meta, sep='\t')

        if args.col_sample not in meta_df.columns or args.col_diag not in meta_df.columns:
            print(f"[!] Error: Columns '{args.col_sample}' or '{args.col_diag}' not found in metadata.")
            sys.exit(1)

        meta_dict = dict(zip(meta_df[args.col_sample].astype(str), meta_df[args.col_diag].astype(str)))

        # Identify missing and unhandled samples (Forward Check)
        otu_orig_names = {item[1] for item in final_samples}
        missing_in_meta = {orig_name for orig_name in otu_orig_names if orig_name not in meta_dict}
        
        # Identify metadata samples missing in OTUs (Reverse Check)
        missing_in_otu = {orig_name for orig_name in meta_dict.keys() if orig_name not in otu_orig_names}

        unhandled_samples = {}
        for final_name, orig_name, proj in final_samples:
            if orig_name in meta_dict:
                diag = meta_dict[orig_name]
                if diag not in args.ibd and diag not in args.non_ibd:
                    unhandled_samples[orig_name] = diag

        unhandled_diagnoses_logs = [f"Sample '{s}' has unmapped diagnosis: '{d}'" for s, d in unhandled_samples.items()]

        # --- LOGGING EXECUTED EARLY TO PREVENT LOSS ON SYS.EXIT ---
        os.makedirs("tmp", exist_ok=True)
        with open("tmp/pipeline_drops.log", "w") as log:
            log.write(f"\n---Script {os.path.basename(__file__)} -------\n\n=== SAMPLES RENAMED/SPLIT DUE TO CONTENT COLLISION ===\n")
            if not renamed_samples: log.write("None\n")
            else: log.write("\n".join(renamed_samples) + "\n")
            
            log.write("\n=== SAMPLES IN OTU MISSING FROM METADATA ===\n")
            if not missing_in_meta: log.write("None\n")
            else: log.write("\n".join(sorted(list(missing_in_meta))) + "\n")

            log.write("\n=== SAMPLES IN METADATA MISSING FROM OTU TABLES ===\n")
            if not missing_in_otu: log.write("None\n")
            else: log.write("\n".join(sorted(list(missing_in_otu))) + "\n")
            
            log.write("\n=== UNHANDLED DIAGNOSES ===\n")
            if not unhandled_diagnoses_logs: log.write("None\n")
            else: log.write("\n".join(sorted(list(unhandled_diagnoses_logs))) + "\n")

        # Interactive check 1: Missing from metadata
        if missing_in_meta:
            print(f"[!] CRITICAL: {len(missing_in_meta)} samples missing in metadata.")
            print(f"Missing samples: {missing_in_meta}")
            
            user_choice = input("Do you want to remove these missing samples from the final OTU table? (Yes/No): ").strip().lower()
            time.sleep(1)
            if user_choice in ['yes', 'y']:
                print(f"   -> Removing {len(missing_in_meta)} missing samples from the pipeline...")
                final_samples = [item for item in final_samples if item[1] not in missing_in_meta]
                dropped_missing_meta = len(missing_in_meta)
            else:
                print("[!] Keeping missing samples. Aborting label generation due to missing metadata.")
                sys.exit(1)

        # Interactive check 2: Unhandled diagnoses
        if unhandled_samples:
            print(f"\n[!] CRITICAL: {len(unhandled_samples)} samples have unhandled diagnoses.")
            unique_diags = set(unhandled_samples.values())
            print(f"   -> Unmapped Diagnosis values found: {', '.join(unique_diags)}")
            print("   -> Check 'tmp/pipeline_drops.log' for the full list of affected samples.")
            
            user_choice = input("Do you want to remove these samples from the final OTU table and labels? (Yes/No): ").strip().lower()
            time.sleep(1)
            if user_choice in ['yes', 'y']:
                print(f"   -> Removing {len(unhandled_samples)} samples with unhandled diagnoses...")
                final_samples = [item for item in final_samples if item[1] not in unhandled_samples]
                dropped_unhandled_diag = len(unhandled_samples)
            else:
                print("Aborting pipeline execution. Please update --ibd or --non_ibd arguments to include these strings.")
                sys.exit(1)

        # Build clean label strings for the retained samples
        for final_name, orig_name, proj in final_samples:
            diag = meta_dict[orig_name]
            if diag in args.ibd: labels_out.append(f"{final_name},1\n")
            elif diag in args.non_ibd: labels_out.append(f"{final_name},0\n")
    else:
        print("\n[!] Warning: Metadata file not provided or not found. Skipping validation and label steps.")

    # 5. Generate the final combined Matrix
    oids = list(data.keys())
    matrix = [[data[oid]['vals'].get(orig, {}).get(proj, 0.0) for _, orig, proj in final_samples] for oid in oids]

    os.makedirs(args.outdir, exist_ok=True)
    out_tsv = os.path.join(args.outdir, "raw_global_otu_dedup.tsv")
    
    print(f"\n4. Saving Merged OTU Table to {out_tsv}...")
    with open(out_tsv, 'w') as fout:
        fout.write("UnifiedID\t" + "\t".join([x[0] for x in final_samples]) + "\tTaxon\n")
        for i, oid in enumerate(oids):
            row = [oid] + [str(matrix[i][j]) for j in range(len(final_samples))] + [data[oid]['tax']]
            fout.write("\t".join(row) + "\n")

    # 6. Extract Reference Sequences to build the Master FASTA
    print("\n5. Extracting Reference Sequences for FASTA generation...")
    gg2_req = {k.replace("GG2:", ""): k for k in oids if k.startswith("GG2:")}
    silva_req = {k.replace("SILVA:", ""): k for k in oids if k.startswith("SILVA:")}
    
    out_fasta = os.path.join(args.outdir, "merged_seqs.fasta")
    
    with open(out_fasta, 'w') as fout:
        if silva_req and os.path.exists(args.silva_fasta):
            print(f"   -> Scanning SILVA Database for {len(silva_req)} required sequences...")
            with open(args.silva_fasta, 'r') as f:
                keep = False
                for line in f:
                    if line.startswith('>'):
                        # Split header into ID and Taxonomy explicitly
                        parts = line[1:].strip().split(' ', 1)
                        h_id = parts[0]
                        if h_id in silva_req:
                            keep = True
                            oid = silva_req[h_id]
                            # Extract taxonomy directly from FASTA header if available
                            tax = parts[1] if len(parts) > 1 else data[oid]['tax']
                            fout.write(f">{oid} {tax}\n")
                        else: keep = False
                    elif keep: fout.write(line)

        if gg2_req and os.path.exists(args.gg2_qza):
            print(f"   -> Scanning GG2 Database for {len(gg2_req)} required sequences...")
            with zipfile.ZipFile(args.gg2_qza, 'r') as z:
                fasta_name = [n for n in z.namelist() if n.endswith('.fasta') or n.endswith('.fna')][0]
                with z.open(fasta_name) as f:
                    keep = False
                    for line in io.TextIOWrapper(f, encoding='utf-8'):
                        if line.startswith('>'):
                            h_id = line[1:].strip().split()[0]
                            if h_id in gg2_req:
                                keep = True
                                oid = gg2_req[h_id]
                                # Clean GG2 prefixes using regex
                                tax = re.sub(r'[a-z]__', '', data[oid]['tax'])
                                fout.write(f">{oid} {tax}\n")
                            else: keep = False
                        elif keep: fout.write(line)

    # 7. Write out Labels CSV if metadata was processed
    if labels_out:
        out_labels = os.path.join(args.outdir, "labels.csv")
        with open(out_labels, 'w') as f:
            f.write("Sample_Name,Label\n")
            f.writelines(labels_out)
        print(f"   [OK] Label CSV successfully generated at: {out_labels}")

    # 8. Print Final Summary Report
    print("\n=================================================")
    print("           === PIPELINE SUMMARY REPORT ===       ")
    print("=================================================")
    print(f" - Initial Unique Samples Processed : {initial_samples_count}")
    print(f" - Samples Dropped (Missing Meta)   : {dropped_missing_meta}")
    print(f" - Samples Dropped (Unhandled Diag) : {dropped_unhandled_diag}")
    print(f" - Metadata Samples Missing in OTU  : {len(missing_in_otu)}")
    print(f" - FINAL SAMPLES RETAINED           : {len(final_samples)}")
    print(f" - FINAL UNIQUE TAXA                : {len(data)}")
    print("=================================================\n")
    print(f"[+] COMPLETE! Saved TSV, Master FASTA, and Labels strictly to: {args.outdir}\n")


def parse_args():
    p = argparse.ArgumentParser(description="Merge unified OTU tables, extract reference sequences, and optionally filter via labels interactively.")
    p.add_argument('-i', '--input_dir', required=True, 
                   help="Directory containing the *_unified_tax.tsv files generated by step 1.")
    p.add_argument('--outdir', default=".output", 
                   help="Directory to save the final merged TSV, extracted FASTA, and labels.")
    p.add_argument('--silva_fasta', default=".Database/silva_data/silva-138.2-ssu-nr99-seqs.fasta", 
                   help="Path to the SILVA reference FASTA file.")
    p.add_argument('--gg2_qza', default=".Database/gg2_data/2024.09.backbone.full-length.fna.qza", 
                   help="Path to the Greengenes2 backbone QZA artifact.")
    p.add_argument('--meta', default="", required=True,
                   help="Path to the clinical metadata (supports .db SQLite databases or .tsv files).")
    p.add_argument('--col_sample', default="sample_id", 
                   help="Name of the column in the metadata file that contains the sequence sample IDs.")
    p.add_argument('--col_diag', default="diagnosis", 
                   help="Name of the column in the metadata file that contains the clinical diagnosis status.")
    p.add_argument('--ibd', nargs='+', default=["IBD-UC", "IBD-CD", "Colorectal Cancer"], 
                   help="List of explicit diagnostic strings to classify as POSITIVE (Label 1).")
    p.add_argument('--non_ibd', nargs='+', default=["Healthy"], 
                   help="List of explicit diagnostic strings to classify as NEGATIVE (Label 0).")
    return p.parse_args()


if __name__ == '__main__':
    main()